#!/usr/bin/env node
/**
 * @fileoverview Generates the MCP App view bundle and the view strings.
 *
 * Two artefacts come out of the view pipeline:
 *
 *  1. `dist/mcp-ui/views.html` — the single-file bundle the MCP server serves
 *     for every `ui://` resource. It is a build artefact, not a source file,
 *     so it stays out of git; the server reads it at runtime.
 *  2. `src/renderer/mcp-views/standalone/generated-strings.ts` — the `mcpViews`
 *     translation namespace extracted from `en-US.json`. The standalone bundle
 *     embeds only the strings it needs instead of all 55 locales, so this
 *     small module is generated and committed.
 *
 * Usage:
 *   node scripts/generate-mcp-ui-views.mjs          # build + generate
 *   node scripts/generate-mcp-ui-views.mjs --strings-only
 */

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const STRINGS_FILE = path.join(ROOT, 'src', 'renderer', 'mcp-views', 'standalone', 'generated-strings.ts');
const LOCALE_FILE = path.join(ROOT, 'src', 'renderer', 'i18n', 'locales', 'en-US.json');
const BUNDLE_FILE = path.join(ROOT, 'dist', 'mcp-ui', 'views.html');

/**
 * Ceiling for the generated bundle, in bytes.
 *
 * The bundle carries React, MUI, the `ext-apps` App class (which pulls the
 * MCP client stack and zod) and every view, so it lands around 880 KB. The
 * budget exists to catch an accidental regression - a duplicated library, an
 * unminified dependency - not to keep the document tiny: the host fetches it
 * once per view resource.
 */
const MAX_BUNDLE_BYTES = 1024 * 1024;

/**
 * Extracts the `mcpViews` namespace from the base locale.
 * @returns {object} The `mcpViews` namespace.
 */
function readViewStrings() {
  const locale = JSON.parse(fs.readFileSync(LOCALE_FILE, 'utf8'));
  if (!locale.mcpViews) {
    throw new Error('en-US.json has no "mcpViews" namespace');
  }
  return locale.mcpViews;
}

/**
 * Writes the generated strings module.
 * @returns {void}
 */
function writeStrings() {
  const strings = readViewStrings();
  const body = `/**
 * @fileoverview Translation strings for the standalone MCP App bundle.
 *
 * GENERATED by \`scripts/generate-mcp-ui-views.mjs\` from
 * \`src/renderer/i18n/locales/en-US.json\` — do not edit by hand.
 *
 * Only the \`mcpViews\` namespace is embedded: the standalone document ships
 * to third-party hosts and must stay small, and hosts do not report a locale
 * yet, so the English strings are the only ones it can use.
 */

/** The \`mcpViews\` namespace of the base locale. @const {object} */
export const MCP_VIEW_STRINGS = ${JSON.stringify(strings, null, 2)} as const;
`;
  fs.writeFileSync(STRINGS_FILE, body);
  process.stdout.write(`[mcp-ui] wrote ${path.relative(ROOT, STRINGS_FILE)}\n`);
}

/**
 * Builds the single-file bundle and checks its size.
 * @returns {void}
 */
function buildBundle() {
  execFileSync(
    process.execPath,
    [path.join(ROOT, 'node_modules', 'vite', 'bin', 'vite.js'), 'build', '--config', 'vite.mcp-ui.config.ts'],
    {
      cwd: ROOT,
      stdio: 'inherit',
    },
  );
  const emitted = path.join(ROOT, 'dist', 'mcp-ui', 'index.html');
  if (!fs.existsSync(emitted)) {
    throw new Error(`The bundle was not produced at ${emitted}`);
  }
  fs.mkdirSync(path.dirname(BUNDLE_FILE), { recursive: true });
  fs.renameSync(emitted, BUNDLE_FILE);
  const size = fs.statSync(BUNDLE_FILE).size;
  process.stdout.write(`[mcp-ui] bundle is ${(size / 1024).toFixed(1)} KB\n`);
  if (size > MAX_BUNDLE_BYTES) {
    throw new Error(`The bundle is ${size} bytes, over the ${MAX_BUNDLE_BYTES} byte budget`);
  }
}

const stringsOnly = process.argv.includes('--strings-only');
writeStrings();
if (!stringsOnly) buildBundle();

import fs from 'fs';
import path from 'path';

/**
 * Generates `src/main/generated/sentryBuildConfig.ts` from the environment so
 * release builds can bake monitoring values (currently the Sentry DSN) into
 * the packaged app. Installed clients have no repo-root .env and end users do
 * not set SENTRY_DSN, so packaged builds need the value compiled in. Runtime
 * environment variables still win at app startup.
 *
 * Value resolution: real SENTRY_DSN env var wins, otherwise the repo-root
 * `.env` entry is used (mirrors the app's runtime dotenv precedence).
 *
 * Usage: SENTRY_DSN=... npm run gen:sentry-config   (or rely on .env)
 */

const OUTPUT_PATH = path.resolve(process.cwd(), 'src/main/generated/sentryBuildConfig.ts');

/** Reads `key` from the repo-root .env without pulling in a dependency. */
function readDotEnvValue(key) {
  let contents;
  try {
    contents = fs.readFileSync(path.resolve(process.cwd(), '.env'), 'utf8');
  } catch {
    return undefined;
  }
  for (const line of contents.split(/\r?\n/)) {
    const match = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (match && match[1] === key) {
      let value = match[2];
      if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
        value = value.slice(1, -1);
      }
      return value || undefined;
    }
  }
  return undefined;
}

const dsn = process.env.SENTRY_DSN?.trim() || readDotEnvValue('SENTRY_DSN') || undefined;

const contents = `/**
 * AUTO-GENERATED by scripts/generate-sentry-config.mjs - DO NOT EDIT.
 *
 * Bakes release-build monitoring configuration (currently the Sentry DSN)
 * into the packaged app, since installed clients cannot rely on shell
 * environment variables or a repo-root .env. A runtime SENTRY_DSN still takes
 * precedence over this value. Regenerate via \`npm run gen:sentry-config\`.
 */

/** Monitoring values captured at build time. @type {{ dsn?: string }} */
export const SENTRY_BUILD_CONFIG = {
  dsn: ${dsn ? JSON.stringify(dsn) : 'undefined'},
};
`;

fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
fs.writeFileSync(OUTPUT_PATH, contents);
console.log(`[INFO] Wrote ${path.relative(process.cwd(), OUTPUT_PATH)} (dsn: ${dsn ? 'set' : 'not set'})`);

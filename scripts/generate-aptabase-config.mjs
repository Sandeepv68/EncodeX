import fs from 'fs';
import path from 'path';

/**
 * Generates `src/main/generated/aptabaseBuildConfig.ts` from the environment so
 * release builds can bake analytics values (the Aptabase App Key, and the
 * optional self-hosted host) into the packaged app. Installed clients have no
 * repo-root .env and end users do not set APTABASE_APP_KEY, so packaged builds
 * need the key compiled in - without it the provider factory falls back to the
 * no-op backend and the dashboard stays empty. Runtime environment variables
 * still win at app startup.
 *
 * Value resolution: real APTABASE_* env vars win, otherwise the repo-root
 * `.env` entry is used (mirrors the app's runtime dotenv precedence).
 *
 * Usage: APTABASE_APP_KEY=... npm run gen:aptabase-config   (or rely on .env)
 */

const OUTPUT_PATH = path.resolve(process.cwd(), 'src/main/generated/aptabaseBuildConfig.ts');

/** Reads `key` from the repo-root .env without pulling in a dependency. */
function readDotEnvValue(key) {
  let contents;
  try {
    contents = fs.readFileSync(path.resolve(process.cwd(), '.env'), 'utf8');
  } catch {
    return undefined;
  }
  for (const line of contents.split(/\r?\n/)) {
    const match = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (match && match[1] === key) {
      let value = match[2];
      if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
        value = value.slice(1, -1);
      }
      return value || undefined;
    }
  }
  return undefined;
}

const appKey = process.env.APTABASE_APP_KEY?.trim() || readDotEnvValue('APTABASE_APP_KEY') || undefined;
const host = process.env.APTABASE_HOST?.trim() || readDotEnvValue('APTABASE_HOST') || undefined;
const environment = process.env.APTABASE_ENVIRONMENT?.trim() || readDotEnvValue('APTABASE_ENVIRONMENT') || undefined;

const contents = `/**
 * AUTO-GENERATED by scripts/generate-aptabase-config.mjs - DO NOT EDIT.
 *
 * Bakes release-build analytics configuration (the Aptabase App Key, the
 * optional self-hosted host, and the environment label) into the packaged
 * app, since installed clients cannot rely on shell environment variables or
 * a repo-root .env. Runtime APTABASE_* values still take precedence over
 * these. Regenerate via \`npm run gen:aptabase-config\`.
 */

/** Analytics values captured at build time. @type {{ appKey?: string, host?: string, environment?: string }} */
export const APTABASE_BUILD_CONFIG = {
  appKey: ${appKey ? JSON.stringify(appKey) : 'undefined'},
  host: ${host ? JSON.stringify(host) : 'undefined'},
  environment: ${environment ? JSON.stringify(environment) : 'undefined'},
};
`;

fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
fs.writeFileSync(OUTPUT_PATH, contents);
console.log(
  `[INFO] Wrote ${path.relative(process.cwd(), OUTPUT_PATH)} (appKey: ${appKey ? 'set' : 'not set'}, host: ${host ? 'set' : 'not set'}, environment: ${environment ? 'set' : 'not set'})`,
);

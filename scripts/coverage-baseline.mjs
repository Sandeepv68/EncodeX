import fs from 'node:fs';
import path from 'node:path';
import { mergeCoverage, assertMergeIsSane } from './coverage-summary.mjs';

/**
 * @fileoverview Records the per-file coverage ratchet baseline.
 *
 * The per-file floor gate (`scripts/coverage-floor-gate.mjs`) is a ratchet, not
 * a fixed threshold. A fixed 80/70 floor cannot be switched on today without
 * failing every build, because dozens of files have never been lifted to it.
 * A ratchet records where each file actually is and refuses to let it fall,
 * so the floor can be raised file by file without ever having to raise it
 * everywhere at once.
 *
 * The baseline file is committed. Regenerating it is an explicit act:
 *
 *     npm run coverage:baseline
 *
 * and a regenerated baseline that *lowers* a file's number is a regression the
 * gate would have caught, so the diff is the review artifact.
 *
 * Usage: `npm run coverage:baseline`.
 */

const BASELINE_FILE = process.env.COVERAGE_BASELINE_FILE ?? 'coverage-baseline.json';
const dirs = (process.env.COVERAGE_DIRS ?? 'coverage,coverage-integration').split(',').map((d) => d.trim());

/**
 * Rounds a percentage to two decimals.
 *
 * Two decimals is enough to distinguish a real regression from the float noise
 * of a merged report, and small enough that the committed file stays readable.
 *
 * @param {number} value - The percentage.
 * @returns {number} The rounded percentage.
 */
function round(value) {
  return Math.round(value * 100) / 100;
}

let merged;
try {
  merged = mergeCoverage(dirs);
  assertMergeIsSane(merged.entries, dirs);
} catch (error) {
  console.error(`Cannot record a coverage baseline: ${error.message}`);
  process.exit(1);
}

const { entries, tiers, skipped } = merged;
if (skipped.length > 0) {
  console.warn(`No raw report in: ${skipped.join(', ')}. Run both coverage tiers first.`);
}

const files = {};
for (const entry of entries) {
  files[entry.file] = {
    // The floor metric: the stricter of lines and statements. A file can have
    // 100% line coverage and lower statement coverage when several statements
    // share a line, and the gate judges the stricter number - so the baseline
    // has to record the same number the gate compares, or every such file
    // looks like a regression.
    lines: round(Math.min(entry.lines, entry.statements)),
    branches: round(entry.branches),
    statements: round(entry.statements),
  };
}

const baseline = {
  $comment:
    'Per-file coverage ratchet. Generated by `npm run coverage:baseline`. The gate ' +
    'refuses to let a file fall below the numbers recorded here, and holds new files to ' +
    'the global floor.',
  generatedFrom: tiers,
  total: {
    lines: round(entries.reduce((sum, e) => sum + e.lines, 0) / entries.length),
    branches: round(entries.reduce((sum, e) => sum + e.branches, 0) / entries.length),
  },
  files,
};

fs.mkdirSync(path.dirname(BASELINE_FILE), { recursive: true });
fs.writeFileSync(BASELINE_FILE, `${JSON.stringify(baseline, null, 2)}\n`, 'utf8');

console.log(`Recorded ${Object.keys(files).length} file(s) -> ${BASELINE_FILE}`);
console.log(`Tiers merged: ${tiers.join(', ')}`);
process.exit(0);

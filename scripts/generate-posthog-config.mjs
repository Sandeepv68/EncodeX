import fs from 'fs';
import path from 'path';
import { parse as parseDotEnv } from 'dotenv';

const OUTPUT_PATH = path.resolve(process.cwd(), 'src/main/generated/posthogBuildConfig.ts');

/**
 * Reads the repo-root .env with dotenv's own parser.
 *
 * The runtime app loads .env through dotenv, where a duplicated key resolves
 * to its *last* occurrence. Parsing here the same way keeps the baked build
 * config identical to what the app sees at runtime.
 * @returns {Record<string, string>} Parsed .env values (empty when absent).
 */
function readDotEnvValues() {
  try {
    const contents = fs.readFileSync(path.resolve(process.cwd(), '.env'), 'utf8');
    return parseDotEnv(contents);
  } catch {
    return {};
  }
}

const dotenvValues = readDotEnvValues();

const projectToken = process.env.POSTHOG_PROJECT_TOKEN?.trim() || dotenvValues.POSTHOG_PROJECT_TOKEN?.trim() || undefined;
const host = process.env.POSTHOG_HOST?.trim() || dotenvValues.POSTHOG_HOST?.trim() || undefined;

const contents = `/**
 * AUTO-GENERATED by scripts/generate-posthog-config.mjs - DO NOT EDIT.
 *
 * Bakes the public PostHog project token and ingestion host into packaged
 * desktop builds, where a repo-root .env is unavailable. Runtime POSTHOG_*
 * values still take precedence. Regenerate via \`npm run gen:posthog-config\`.
 */
export const POSTHOG_BUILD_CONFIG = {
  projectToken: ${projectToken ? JSON.stringify(projectToken) : 'undefined'},
  host: ${host ? JSON.stringify(host) : 'undefined'},
};
`;

fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
fs.writeFileSync(OUTPUT_PATH, contents);
console.log(
  `[INFO] Wrote ${path.relative(process.cwd(), OUTPUT_PATH)} (projectToken: ${projectToken ? 'set' : 'not set'}, host: ${host ? 'set' : 'not set'})`,
);

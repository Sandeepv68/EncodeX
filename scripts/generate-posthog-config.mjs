import fs from 'fs';
import path from 'path';

const OUTPUT_PATH = path.resolve(process.cwd(), 'src/main/generated/posthogBuildConfig.ts');

function readDotEnvValue(key) {
  let contents;
  try {
    contents = fs.readFileSync(path.resolve(process.cwd(), '.env'), 'utf8');
  } catch {
    return undefined;
  }
  for (const line of contents.split(/\r?\n/)) {
    const match = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (match && match[1] === key) {
      let value = match[2];
      if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
        value = value.slice(1, -1);
      }
      return value || undefined;
    }
  }
  return undefined;
}

const projectToken = process.env.POSTHOG_PROJECT_TOKEN?.trim() || readDotEnvValue('POSTHOG_PROJECT_TOKEN') || undefined;
const host = process.env.POSTHOG_HOST?.trim() || readDotEnvValue('POSTHOG_HOST') || undefined;

const contents = `/**
 * AUTO-GENERATED by scripts/generate-posthog-config.mjs - DO NOT EDIT.
 *
 * Bakes the public PostHog project token and ingestion host into packaged
 * desktop builds, where a repo-root .env is unavailable. Runtime POSTHOG_*
 * values still take precedence. Regenerate via \`npm run gen:posthog-config\`.
 */
export const POSTHOG_BUILD_CONFIG = {
  projectToken: ${projectToken ? JSON.stringify(projectToken) : 'undefined'},
  host: ${host ? JSON.stringify(host) : 'undefined'},
};
`;

fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
fs.writeFileSync(OUTPUT_PATH, contents);
console.log(`[INFO] Wrote ${path.relative(process.cwd(), OUTPUT_PATH)} (projectToken: ${projectToken ? 'set' : 'not set'}, host: ${host ? 'set' : 'not set'})`);
